import { useEffect, useState } from "react";
import { api } from "./api";
import { latestDayWithData } from "./dates";
import { AlertsTable } from "./components/AlertsTable";
import { DistrictTable } from "./components/DistrictTable";
import { MessageBox } from "./components/MessageBox";
import { Section } from "./components/Section";
import { SummaryCards } from "./components/SummaryCards";
import { TrendChart } from "./components/TrendChart";
import { useLoad } from "./useLoad";

export default function App() {
  // Held in memory only: never written to localStorage or cookies.
  const [apiKey, setApiKey] = useState("");
  const [date, setDate] = useState<string | null>(null);

  const trend = useLoad(() => api.trend(30), []);
  const daily = useLoad(() => api.daily(date ?? undefined), [date]);
  const alerts = useLoad(() => api.openAlerts(), []);

  useEffect(() => {
    if (date === null && trend.data) setDate(latestDayWithData(trend.data) ?? new Date().toISOString().slice(0, 10));
  }, [trend.data, date]);

  const refreshAll = () => {
    trend.reload();
    daily.reload();
    alerts.reload();
  };

  return (
    <div className="page">
      <div className="banner" role="note">Demo with synthetic data.</div>
      <header className="top">
        <h1>MealTrack</h1>
        <div className="controls">
          <label>
            Date
            <input type="date" value={date ?? ""} onChange={(e) => e.target.value && setDate(e.target.value)} />
          </label>
          <label>
            API key (for write actions)
            <input
              type="password"
              value={apiKey}
              autoComplete="off"
              placeholder="X-API-Key"
              onChange={(e) => setApiKey(e.target.value)}
            />
          </label>
        </div>
      </header>

      <SummaryCards state={daily} />

      <Section title="Total meals, last 30 days" state={trend}>
        {(points) => <TrendChart points={points} />}
      </Section>

      <div className="two-col">
        <Section title="Districts" state={daily}>
          {(s) => <DistrictTable rows={s.byDistrict} />}
        </Section>
        <section className="card">
          <header className="card-head">
            <h2>Message box</h2>
          </header>
          <MessageBox apiKey={apiKey} onSaved={refreshAll} />
        </section>
      </div>

      <Section title="Open alerts" state={alerts}>
        {(list) => <AlertsTable alerts={list} apiKey={apiKey} onResolved={refreshAll} />}
      </Section>

      <footer className="muted foot">
        All figures are generated by a seed script. Not affiliated with Feeding India; no real data.
      </footer>
    </div>
  );
}
